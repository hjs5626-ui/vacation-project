const RECENT_KEY = 'memento_emoji_recent';
const RECENT_LIMIT = 24;

export function getRecentEmojis() {
  try {
    const raw = JSON.parse(localStorage.getItem(RECENT_KEY) || '[]');
    return Array.isArray(raw) ? raw.filter((c) => typeof c === 'string') : [];
  } catch {
    return [];
  }
}

export function rememberEmoji(char) {
  if (!char) return;
  const next = [char, ...getRecentEmojis().filter((c) => c !== char)].slice(0, RECENT_LIMIT);
  try {
    localStorage.setItem(RECENT_KEY, JSON.stringify(next));
  } catch { /* ignore quota */ }
}

export function allEmojis() {
  return EMOJI_CATEGORIES.flatMap((cat) => cat.items);
}

export function searchEmojis(query) {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return allEmojis();
  return allEmojis().filter((item) =>
    item.char.includes(q) || item.keywords.toLowerCase().includes(q)
  );
}
